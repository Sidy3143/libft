int	ft_isalnum(char *s)
{
	int i;

	i = 0;
	while (s[i])
	{
		if (!(('0' <= s[i] && s[i] <= '9') || ('a' <= s[i] && s[i] <= 'z') || ('A' <= s[i] && s[i] <= 'Z')))
			return (0);
        i++;
	}
	return (1);
}